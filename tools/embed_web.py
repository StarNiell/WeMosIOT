"""Embed the web page in the firmware.

Compresses web/index.html with gzip and writes it as a byte array to
src/web_assets.h. PlatformIO runs this script before every build
(extra_scripts = pre:tools/embed_web.py); it can also be run by hand:

    python3 tools/embed_web.py

The header is rewritten only when its content changes, so an unchanged
page does not trigger a rebuild.
"""
import gzip
import os
import sys

try:
    Import("env")  # noqa: F821  (defined when run by PlatformIO / SCons)
    PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(sys.argv[0])))

SOURCE = os.path.join(PROJECT_DIR, "web", "index.html")
TARGET = os.path.join(PROJECT_DIR, "src", "web_assets.h")


def build_header(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return (
        "// web_assets.h - GENERATED by tools/embed_web.py from web/index.html.\n"
        "// Do not edit: change web/index.html and rebuild.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        "static const size_t INDEX_HTML_GZ_LEN = %d;\n"
        "static const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n%s\n};\n"
        % (len(data), "\n".join(lines))
    )


def main() -> None:
    with open(SOURCE, "rb") as f:
        html = f.read()
    # mtime=0 keeps the output identical for identical input
    data = gzip.compress(html, compresslevel=9, mtime=0)
    header = build_header(data)

    old = None
    if os.path.exists(TARGET):
        with open(TARGET, "r", encoding="utf-8") as f:
            old = f.read()
    if old != header:
        with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
            f.write(header)
        print("embed_web: %s updated (%d -> %d bytes gzip)" % (TARGET, len(html), len(data)))


main()
